import type { RoundTableChatMessage, ThinkTankAnalysis } from "@/components/roundtable/types";
import { sortDisplayNames } from "@/lib/figure-sort";

function formatTranscript(messages: RoundTableChatMessage[]): string {
  return messages
    .map((m) => {
      if (m.role === "user") {
        const text = m.content.replace(/^Moderator:\s*/i, "");
        return `### Round Table Moderator\n\n${text}\n`;
      }
      return `### ${m.figureName ?? "Figure"} (${m.era ?? ""})\n\n> ${m.content}\n`;
    })
    .join("\n");
}

function formatAnalysisSections(analysis: ThinkTankAnalysis): string {
  return [
    "## Consensus",
    analysis.consensus,
    "",
    "## Disagreements",
    analysis.disagreements,
    "",
    "## Risks",
    analysis.risks,
    "",
    "## Recommendations",
    analysis.recommendations,
    "",
    "## Executive Summary",
    analysis.executiveSummary,
  ].join("\n");
}

export function buildDebateMarkdown(params: {
  topicTitle: string;
  topicFull?: string;
  messages: RoundTableChatMessage[];
  analysis?: ThinkTankAnalysis | null;
  participantNames?: string[];
}): string {
  const { topicTitle, topicFull, messages, analysis, participantNames } = params;
  const lines: string[] = [
    `# FMS Think Tank — Historical Round Table`,
    "",
    `**Topic:** ${topicTitle}`,
  ];

  if (topicFull && topicFull !== topicTitle) {
    lines.push("", topicFull);
  }

  if (participantNames?.length) {
    lines.push(
      "",
      `**Participants:** ${sortDisplayNames(participantNames).join(", ")}`,
    );
  }

  lines.push("", "---", "", "## Transcript", "", formatTranscript(messages));

  if (analysis) {
    lines.push("", "---", "", "## Think Tank Analysis", "", formatAnalysisSections(analysis));
  }

  lines.push("", "---", "", "*Generated by FMS Expert Agents — Historical Round Table*");
  return lines.join("\n");
}

export function buildResearchBriefMarkdown(params: {
  topicTitle: string;
  analysis: ThinkTankAnalysis;
  messages: RoundTableChatMessage[];
}): string {
  const { topicTitle, analysis, messages } = params;
  const exchangeCount = messages.filter((m) => m.role === "assistant").length;

  return [
    `# Research Brief`,
    "",
    `**Subject:** ${topicTitle}`,
    `**Date:** ${new Date().toLocaleDateString("en-GB", { dateStyle: "long" })}`,
    `**Exchanges reviewed:** ${exchangeCount}`,
    "",
    "## Executive Summary",
    analysis.executiveSummary,
    "",
    "## Key Findings",
    "### Areas of Consensus",
    analysis.consensus,
    "",
    "### Points of Contention",
    analysis.disagreements,
    "",
    "## Risk Assessment",
    analysis.risks,
    "",
    "## Policy Implications",
    analysis.recommendations,
    "",
    "---",
    "*FMS Think Tank — Historical Round Table Research Brief*",
  ].join("\n");
}

