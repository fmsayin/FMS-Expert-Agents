export function downloadTextFile(filename: string, content: string, mime = "text/markdown"): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function openPrintView(html: string, title: string): void {
  const printWindow = window.open("", "_blank", "noopener,noreferrer");
  if (!printWindow) return;

  printWindow.document.write(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>${title}</title>
  <style>
    @page { margin: 2cm; }
    body {
      font-family: Georgia, "Times New Roman", serif;
      font-size: 11pt;
      line-height: 1.5;
      color: #1a1208;
      max-width: 720px;
      margin: 0 auto;
      padding: 1rem;
    }
    h1 { font-size: 18pt; border-bottom: 1px solid #c4a574; padding-bottom: 0.5rem; }
    h2 { font-size: 13pt; margin-top: 1.5rem; color: #6b5c3e; }
    h3 { font-size: 11pt; margin-top: 1rem; }
    blockquote {
      margin: 0.5rem 0 1rem 1rem;
      padding-left: 0.75rem;
      border-left: 3px solid #8b6914;
      font-style: italic;
    }
    .moderator {
      background: #f4ead5;
      padding: 0.75rem 1rem;
      border-radius: 4px;
      margin: 1rem 0;
    }
    hr { border: none; border-top: 1px solid #c4a574; margin: 1.5rem 0; }
    @media print {
      body { padding: 0; }
    }
  </style>
</head>
<body>${html}</body>
</html>`);
  printWindow.document.close();
  printWindow.focus();
  setTimeout(() => {
    printWindow.print();
  }, 300);
}

export function markdownToPrintHtml(markdown: string): string {
  return markdown
    .replace(/^# (.+)$/gm, "<h1>$1</h1>")
    .replace(/^## (.+)$/gm, "<h2>$1</h2>")
    .replace(/^### (.+)$/gm, "<h3>$1</h3>")
    .replace(/^> (.+)$/gm, "<blockquote>$1</blockquote>")
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/\n\n/g, "</p><p>")
    .replace(/^(.+)$/gm, (line) => {
      if (line.startsWith("<")) return line;
      return line;
    });
}
